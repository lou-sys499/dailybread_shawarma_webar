// POST /api/rewards/validate-coupon - Validate coupon without immediate redemption
app.post('/api/rewards/validate-coupon', async (req, res) => {
  const { code } = req.body;
  if (!code || typeof code !== 'string') {
    return res.status(400).json({ success: false, valid: false, error: 'Coupon code is required.' });
  }

  const query = code.trim();
  const now = new Date();
  const client = getSupabaseClient();

  if (client) {
    try {
      const isUuid = isValidUuid(query);
      let fetchQuery = client.from('cyberwrap_coupons').select('*');
      if (isUuid) {
        fetchQuery = fetchQuery.or(`code_hash.ilike.${query},id.eq.${query}`);
      } else {
        fetchQuery = fetchQuery.ilike('code_hash', query);
      }
      const { data, error } = await fetchQuery.maybeSingle();

      if (!error && data) {
        const isExpired = data.status === 'expired' || (data.status === 'active' && new Date(data.expires_at).getTime() <= now.getTime());
        if (isExpired) {
          return res.status(400).json({ success: false, valid: false, error: `Coupon ${data.code_hash} is expired.` });
        }
        if (data.status !== 'active') {
          return res.status(400).json({ success: false, valid: false, error: `Coupon is ${data.status.toUpperCase()} and cannot be used.` });
        }

        return res.json({
          success: true,
          valid: true,
          coupon: data,
          discountPercent: data.discount_percent || 20,
          message: `Valid coupon! ${data.discount_percent || 20}% discount applied to your order.`
        });
      }
    } catch (err) {
      console.warn('Supabase coupon validation error:', err);
    }
  }

  const coupon = inMemoryCoupons.find(c => c.code_hash.toLowerCase() === query.toLowerCase() || c.id === query);
  if (!coupon) {
    return res.status(404).json({ success: false, valid: false, error: 'Coupon code not recognized. Check the spelling or play CyberWrap Arcade to earn one!' });
  }

  const isExpired = coupon.status === 'expired' || (coupon.status === 'active' && new Date(coupon.expires_at).getTime() <= now.getTime());
  if (isExpired) {
    coupon.status = 'expired';
    return res.status(400).json({ success: false, valid: false, error: `Coupon ${coupon.code_hash} is expired.` });
  }
  if (coupon.status !== 'active') {
    return res.status(400).json({ success: false, valid: false, error: `Coupon is ${coupon.status.toUpperCase()} and cannot be used.` });
  }

  return res.json({
    success: true,
    valid: true,
    coupon,
    discountPercent: coupon.discount_percent || 20,
    message: `Valid coupon! ${coupon.discount_percent || 20}% discount applied to your order.`
  });
});

// POST /api/rewards/redeem-coupon - Redeem active voucher
app.post('/api/rewards/redeem-coupon', async (req, res) => {
  const { codeOrId, orderValueXaf } = req.body;

  if (!codeOrId) {
    return res.status(400).json({ error: 'codeOrId is required.' });
  }

  const query = codeOrId.trim();
  const now = new Date();
  const nowIso = now.toISOString();
  const client = getSupabaseClient();

  if (client) {
    try {
      const isUuid = isValidUuid(query);
      let fetchQuery = client.from('cyberwrap_coupons').select('*');
      if (isUuid) {
        fetchQuery = fetchQuery.or(`code_hash.eq.${query},id.eq.${query}`);
      } else {
        fetchQuery = fetchQuery.eq('code_hash', query);
      }
      const { data, error } = await fetchQuery.maybeSingle();

      if (!error && data) {
        // Enforce server-side expiration validation
        const isExpired = data.status === 'expired' || (data.status === 'active' && new Date(data.expires_at).getTime() <= now.getTime());
        if (isExpired) {
          return res.status(400).json({ error: `Coupon ${data.code_hash} is EXPIRED and cannot be redeemed.` });
        }
        if (data.status !== 'active') {
          return res.status(400).json({ error: `Coupon is currently ${data.status.toUpperCase()} and cannot be applied.` });
        }

        await client
          .from('cyberwrap_coupons')
          .update({ status: 'redeemed', redeemed_at: nowIso })
          .eq('id', data.id);

        const redeemSessId = `sess_redeem_${Math.floor(Math.random() * 9000 + 1000)}`;

        // Log coupon_redeemed analytics event
        try {
          await client
            .from('analytics_events')
            .insert([{
              session_id: redeemSessId,
              campaign: 'Summer Shawarma Splash',
              event: 'coupon_redeemed',
              timestamp: Date.now(),
              game_version: 'v1.4.2',
              data: {
                coupon_id: data.id,
                coupon_code: data.code_hash,
                discount: `${data.discount_percent}%`,
                order_value_xaf: orderValueXaf || 3500,
                player_id: data.player_id
              },
              player_id: data.player_id
            }]);
        } catch (eventErr) {
          console.warn('Supabase coupon_redeemed event logging error:', eventErr);
        }

        return res.json({
          success: true,
          coupon: { ...data, status: 'redeemed', redeemed_at: nowIso },
          discountPercent: data.discount_percent,
          message: `Voucher ${data.code_hash} successfully redeemed (-${data.discount_percent}% applied).`
        });
      }
    } catch (err: any) {
      console.warn('Supabase coupon redeem lookup failed:', err);
    }
  }

  const coupon = inMemoryCoupons.find(c => c.code_hash.toLowerCase() === query.toLowerCase() || c.id === query);
  if (!coupon) {
    return res.status(404).json({ error: 'Coupon code not found in registry.' });
  }

  const isExpired = coupon.status === 'expired' || (coupon.status === 'active' && new Date(coupon.expires_at).getTime() <= now.getTime());
  if (isExpired) {
    coupon.status = 'expired';
    return res.status(400).json({ error: `Coupon is EXPIRED and cannot be redeemed.` });
  }

  if (coupon.status !== 'active') {
    return res.status(400).json({ error: `Coupon is ${coupon.status.toUpperCase()} and cannot be redeemed.` });
  }

  coupon.status = 'redeemed';
  coupon.redeemed_at = nowIso;

  // Log redemption event
  inMemoryEvents.unshift({
    id: Date.now(),
    session_id: `sess_redeem_${Math.floor(Math.random() * 9000 + 1000)}`,
    campaign: 'Summer Shawarma Splash',
    event: 'coupon_redeemed',
    timestamp: Date.now(),
    game_version: 'v1.4.2',
    data: { coupon_code: coupon.code_hash, discount: `${coupon.discount_percent}%`, order_value_xaf: orderValueXaf || 3500 },
    created_at: nowIso,
    player_id: coupon.player_id
  });

  res.json({
    success: true,
    coupon,
    discountPercent: coupon.discount_percent,
    message: `Voucher ${coupon.code_hash} successfully redeemed (-${coupon.discount_percent}% applied).`
  });
});

// Fallback static route for 3D model smoothie.glb requests
app.get(['/smoothie.glb', '/public/smoothie.glb'], (req, res) => {
  const primaryPath = path.join(process.cwd(), 'public', 'smoothie.glb');
  const fallbackPath = path.join(process.cwd(), 'public', '3d_shawarma_sample-specimen-v1.glb');
  if (fs.existsSync(primaryPath)) {
    res.sendFile(primaryPath);
  } else if (fs.existsSync(fallbackPath)) {
    res.sendFile(fallbackPath);
  } else {
    res.status(404).send('3D Model not found');
  }
});

